// Turns the desktop's flat icon set (ICON_PATHS in src/webapp-html.js) into
// Kotlin path data for the Android app, so both draw the same icons.
//
//   node android/tools/gen-icons.mjs        (from the repository root)
//
// Writes android/app/src/main/java/mv/obitech/crundi/ui/icons/IconPaths.kt.
// Every SVG shape (path, line, polyline, polygon, circle, rect) becomes one
// path string; CrundiIcons.kt builds stroked ImageVectors from them. Run it
// again whenever ICON_PATHS changes; IconPathsTest fails until you do.
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const root = join(here, '..', '..');

export function readIconPaths(html) {
  const start = html.indexOf('const ICON_PATHS = {');
  if (start < 0) throw new Error('ICON_PATHS not found');
  const end = html.indexOf('\n    };', start);
  const body = html.slice(start, end);
  const out = {};
  const re = /^\s*('([^']+)'|([A-Za-z0-9_-]+)):\s*'([^']*)',?\s*$/gm;
  let m;
  while ((m = re.exec(body))) out[m[2] || m[3]] = m[4];
  return out;
}

const num = (s) => Number.parseFloat(s);
const attrs = (tag) => {
  const a = {};
  for (const m of tag.matchAll(/([a-zA-Z0-9-]+)="([^"]*)"/g)) a[m[1]] = m[2];
  return a;
};
const fmt = (n) => String(Math.round(n * 1000) / 1000);

export function shapesToPaths(svg) {
  const paths = [];
  for (const m of svg.matchAll(/<(path|line|polyline|polygon|circle|rect)\b([^>]*)\/?>/g)) {
    const kind = m[1];
    const a = attrs(m[2]);
    if (kind === 'path') paths.push(a.d);
    else if (kind === 'line') paths.push(`M${a.x1} ${a.y1}L${a.x2} ${a.y2}`);
    else if (kind === 'polyline' || kind === 'polygon') {
      const p = a.points.trim().split(/[\s,]+/).map(num);
      let d = `M${fmt(p[0])} ${fmt(p[1])}`;
      for (let i = 2; i + 1 < p.length; i += 2) d += `L${fmt(p[i])} ${fmt(p[i + 1])}`;
      paths.push(kind === 'polygon' ? d + 'Z' : d);
    } else if (kind === 'circle') {
      const cx = num(a.cx), cy = num(a.cy), r = num(a.r);
      paths.push(`M${fmt(cx - r)} ${fmt(cy)}a${fmt(r)} ${fmt(r)} 0 1 0 ${fmt(2 * r)} 0a${fmt(r)} ${fmt(r)} 0 1 0 ${fmt(-2 * r)} 0Z`);
    } else if (kind === 'rect') {
      const x = num(a.x || '0'), y = num(a.y || '0'), w = num(a.width), h = num(a.height);
      let rx = num(a.rx ?? a.ry ?? '0'), ry = num(a.ry ?? a.rx ?? '0');
      rx = Math.min(rx || 0, w / 2); ry = Math.min(ry || 0, h / 2);
      if (!rx || !ry) paths.push(`M${fmt(x)} ${fmt(y)}h${fmt(w)}v${fmt(h)}h${fmt(-w)}Z`);
      else paths.push(
        `M${fmt(x + rx)} ${fmt(y)}h${fmt(w - 2 * rx)}a${fmt(rx)} ${fmt(ry)} 0 0 1 ${fmt(rx)} ${fmt(ry)}` +
        `v${fmt(h - 2 * ry)}a${fmt(rx)} ${fmt(ry)} 0 0 1 ${fmt(-rx)} ${fmt(ry)}` +
        `h${fmt(-(w - 2 * rx))}a${fmt(rx)} ${fmt(ry)} 0 0 1 ${fmt(-rx)} ${fmt(-ry)}` +
        `v${fmt(-(h - 2 * ry))}a${fmt(rx)} ${fmt(ry)} 0 0 1 ${fmt(rx)} ${fmt(-ry)}Z`);
    }
  }
  return paths;
}

const kstr = (s) => '"' + s.replace(/\\/g, '\\\\').replace(/"/g, '\\"').replace(/\$/g, '\\$') + '"';

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const desk = readIconPaths(readFileSync(join(root, 'src', 'webapp-html.js'), 'utf8'));
  const extra = JSON.parse(readFileSync(join(here, 'icons-extra.json'), 'utf8'));
  delete extra._note;
  const all = { ...extra, ...desk };
  const names = Object.keys(all).sort();
  let kt = '// GENERATED by android/tools/gen-icons.mjs from ICON_PATHS in src/webapp-html.js\n' +
    '// (and android/tools/icons-extra.json). Do not edit: run the script again.\n' +
    'package mv.obitech.crundi.ui.icons\n\n' +
    '/** Each icon\'s shapes as SVG path data, on a 24 by 24 grid, drawn as 2-wide round strokes. */\n' +
    'internal object IconPaths {\n' +
    '    /** Names that come from the desktop\'s ICON_PATHS (the rest are from icons-extra.json). */\n' +
    '    val desktop: Set<String> = setOf(' + Object.keys(desk).sort().map(kstr).join(', ') + ')\n\n' +
    '    val all: Map<String, List<String>> = mapOf(\n';
  for (const n of names) kt += `        ${kstr(n)} to listOf(${shapesToPaths(all[n]).map(kstr).join(', ')}),\n`;
  kt += '    )\n}\n';
  const out = join(root, 'android', 'app', 'src', 'main', 'java', 'mv', 'obitech', 'crundi', 'ui', 'icons', 'IconPaths.kt');
  writeFileSync(out, kt);
  console.log(`wrote ${names.length} icons (${Object.keys(desk).length} from ICON_PATHS) to ${out}`);
}
