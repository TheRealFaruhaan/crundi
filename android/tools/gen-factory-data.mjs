// What the Android factory editor needs from the server's own modules, so the
// phone offers exactly what the web editor offers: the persona templates
// (src/factory-personas.js), the permission presets and the Manager's default
// persona (src/factory-model.js), and the default change request form
// (src/factory-cr.js).
//
//   node android/tools/gen-factory-data.mjs        (from the repository root)
//
// Writes android/app/src/main/resources/mv/obitech/crundi/factory-editor-data.json,
// and, for the Android tests, every provided template as the server hands it
// out (android/app/src/test/resources/api/factory-template-<id>.json).
// scripts/test-android-factory-data.mjs (npm run check) fails when the first
// is out of step: run this again.
import { writeFileSync, mkdirSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { PERSONAS, READ_ONLY } from '../../src/factory-personas.js';
import { PERMISSION_PRESETS, DEFAULT_PRESETS, DEFAULT_MANAGER_PERSONA, validateFactory } from '../../src/factory-model.js';
import { DEFAULT_CR_TEMPLATE, CR_LIMITS } from '../../src/factory-cr.js';
import { factoryTemplates } from '../../src/factory-templates.js';

const here = dirname(fileURLToPath(import.meta.url));
export const DATA_PATH = join(here, '..', 'app', 'src', 'main', 'resources', 'mv', 'obitech', 'crundi', 'factory-editor-data.json');

export function editorData() {
  return {
    _note: 'GENERATED by android/tools/gen-factory-data.mjs from src/factory-personas.js, src/factory-model.js and src/factory-cr.js. Do not edit: run the script again.',
    personas: PERSONAS.map(p => ({ key: p.key, name: p.name, memory: p.memory, deny: [...p.deny], skills: [...p.skills], presets: [...(p.presets || [])], persona: p.persona })),
    readOnly: [...READ_ONLY],
    presets: Object.entries(PERMISSION_PRESETS).map(([key, p]) => ({ key, label: p.label })),
    defaultPresets: [...DEFAULT_PRESETS],
    managerPersona: DEFAULT_MANAGER_PERSONA,
    crTemplate: DEFAULT_CR_TEMPLATE.map(s => ({ ...s })),
    crLimits: { ...CR_LIMITS },
  };
}

export const text = (o) => JSON.stringify(o, null, 2) + '\n';

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  mkdirSync(dirname(DATA_PATH), { recursive: true });
  writeFileSync(DATA_PATH, text(editorData()));
  console.log('wrote', DATA_PATH);
  const fixtures = join(here, '..', 'app', 'src', 'test', 'resources', 'api');
  for (const t of factoryTemplates()) {
    const { template: _t, goodFor: _g, ...def } = t;
    const factory = { ...def, id: 'fac_' + t.id.replace(/^tpl_/, ''), version: 3, createdAt: '2026-10-20T09:00:00.000Z', updatedAt: '2026-10-23T18:30:00.000Z' };
    const file = join(fixtures, 'factory-template-' + t.id.replace(/^tpl_/, '') + '.json');
    writeFileSync(file, text({ ok: true, factory, validation: validateFactory(factory) }));
    console.log('wrote', file);
  }
}
